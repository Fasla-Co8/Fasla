export function seededShuffle<T>(items: T[], seed: string) {
  let hash = 2166136261;
  for (const char of seed) hash = Math.imul(hash ^ char.charCodeAt(0), 16777619);
  const next = [...items];
  for (let index = next.length - 1; index > 0; index -= 1) {
    hash = Math.imul(hash ^ (hash >>> 16), 2246822519);
    const swap = Math.abs(hash) % (index + 1);
    const current = next[index];
    next[index] = next[swap] as T;
    next[swap] = current as T;
  }
  return next;
}

export function buildPresentation(question: BankQuestion, seed: string): Presentation {
  const presentation: Presentation = {};
  if (question.tokens) {
    let tokens = seededShuffle(question.tokens, `${seed}:tokens`);
    const correct = question.correctTokens?.join(" ") ?? "";
    if (tokens.map((token) => token.text).join(" ") === correct && tokens.length > 1) {
      tokens = [tokens[1] as (typeof tokens)[number], tokens[0] as (typeof tokens)[number], ...tokens.slice(2)];
    }
    presentation.tokens = tokens;
  }
  if (question.right) {
    presentation.right = seededShuffle(question.right, `${seed}:right`);
  }
  if (question.scramble) {
    const letters = question.scramble.split("").map((char, index) => ({ id: `${question.id}-l${index}`, char }));
    let shuffled = seededShuffle(letters, `${seed}:letters`);
    if (shuffled.map((letter) => letter.char).join("") === question.scramble && shuffled.length > 1) {
      shuffled = [shuffled[1] as (typeof shuffled)[number], shuffled[0] as (typeof shuffled)[number], ...shuffled.slice(2)];
    }
    presentation.letters = shuffled;
  }
  return presentation;
}

export function toPublic(question: BankQuestion, presentation?: Presentation): PublicQuestion {
  return {
    id: question.id,
    level: question.level,
    type: question.type,
    skill: question.skill,
    stem: question.stem,
    seconds: secondsFor(question.type),
    options: question.options,
    left: question.left,
    right: presentation?.right ?? question.right,
    tokens: presentation?.tokens ?? question.tokens,
    words: question.words?.map((text, index) => ({ index, text })),
    letters: presentation?.letters,
    requiredWord: question.requiredWord,
    minWords: question.minWords,
    listenText: question.transcript,
  };
}
